import re

def normalize_phone(phone_number):
    """ Функція бере номер телефону в будь-якому вигляді і перетворює його на такий, який підходить для надсилання SMS
        Вона прибирає всі зайві символи, залишає тільки цифри і плюс
        Якщо номер уже починається з плюса, вона просто очищає його від зайвого
        Якщо номер починається з 380, але без плюса — додає плюс
        Якщо номер починається просто з 050, 067, 095 тощо — додає код +38
        Повертає чистий номер у форматі, наприклад: +380501234567"""
    cleaned = re.sub(r'[^\d+]', '', phone_number.strip())
    if cleaned.startswith('+'):
        return '+' + re.sub(r'\D', '', cleaned[1:])
    elif cleaned.startswith('380'):
        return '+{}'.format(cleaned)
    else:
        return '+38{}'.format(cleaned)

raw_numbers = [
    "067\\t123 4567",
    "(095) 234-5678\\n",
    "+380 44 123 4567",
    "380501234567",
    "    +38(050)123-32-34",
    "     0503451234",
    "(050)8889900",
    "38050-111-22-22",
    "38050 111 22 11   ",
]

sanitized_numbers = [normalize_phone(num) for num in raw_numbers]
print("Нормалізовані номери телефонів для SMS-розсилки:", sanitized_numbers)